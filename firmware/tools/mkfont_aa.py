"""Generate src/fonts_aa.h: anti-aliased (4-bit alpha) proportional fonts from DejaVu.

Each glyph is stored as a full cell (advance width, widened where the ink runs past it, x line
height), 2 pixels per byte,
row-major, high nibble first. Characters outside a font's set have width 0.

usage: mkfont_aa.py <output.h>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

DIR = "/usr/share/fonts/truetype/dejavu/"
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
FONTS = [
    # name, file, size (px em), characters
    ("font_call", "DejaVuSansCondensed-Bold.ttf", 62, "0CFM"),
    ("font_big", "DejaVuSansCondensed-Bold.ttf", 46, " -.0123456789"),
    ("font_med", "DejaVuSansCondensed-Bold.ttf", 22, ASCII),
    ("font_small", "DejaVuSansCondensed-Bold.ttf", 17, ASCII),
    ("font_med2", "DejaVuSans-Bold.ttf", 21, ASCII),
    ("font_small2", "DejaVuSans-Bold.ttf", 16, ASCII),
]


def render(path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    h = ascent + descent
    first, last = ord(min(chars)), ord(max(chars))
    widths, offsets, data = [], [], bytearray()
    for code in range(first, last + 1):
        ch = chr(code)
        offsets.append(len(data))
        if ch not in chars:
            widths.append(0)
            continue
        left, _, right, _ = font.getbbox(ch, anchor="ls")
        x0 = min(0, left)
        w = max(1, max(round(font.getlength(ch)), right) - x0)
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, ascent), ch, font=font, fill=255, anchor="ls")
        px = list(img.getdata())
        nib = [min(15, (p + 8) // 17) for p in px]
        if len(nib) % 2:
            nib.append(0)
        for i in range(0, len(nib), 2):
            data.append(nib[i] << 4 | nib[i + 1])
        widths.append(w)
    return font, first, last, h, ascent, widths, offsets, data


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/fonts_aa.h"
    lines = ["/* Generated by tools/mkfont_aa.py from the DejaVu fonts (see ATTRIBUTION.md). */",
             "#ifndef FONTS_AA_H", "#define FONTS_AA_H", "#include <stdint.h>", "",
             "typedef struct {",
             "    uint8_t first, last, height, baseline;",
             "    const uint8_t *width;",
             "    const uint32_t *offset;",
             "    const uint8_t *data;",
             "} aafont_t;", ""]
    total = 0
    for name, file, size, chars in FONTS:
        font, first, last, h, base, widths, offsets, data = render(DIR + file, size, chars)
        total += len(data)
        lines.append(f"/* {file} {size} px: {last - first + 1} codes, height {h}, {len(data)} bytes */")
        lines.append(f"static const uint8_t {name}_width[] = {{ {', '.join(map(str, widths))} }};")
        lines.append(f"static const uint32_t {name}_offset[] = {{ {', '.join(map(str, offsets))} }};")
        lines.append(f"static const uint8_t {name}_data[] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const aafont_t {name} = {{ {first}, {last}, {h}, {base}, "
                     f"{name}_width, {name}_offset, {name}_data }};")
        lines.append("")
        for s in ("446.006", "25", "M0FCC", "iRadio UV98+", "Open Firmware v1.0", "NFM", "T88.5", "D023N"):
            if all(c in chars for c in s):
                print(f"{name}: '{s}' is {round(sum(font.getlength(c) for c in s))} px wide")
    lines.append("#endif")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out}: {total} bytes of glyph data")


if __name__ == "__main__":
    main()
